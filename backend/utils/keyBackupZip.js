const path = require('path');
const zlib = require('zlib');

const EOCD_SIGNATURE = 0x06054b50;
const CD_SIGNATURE = 0x02014b50;
const LOCAL_SIGNATURE = 0x04034b50;

const DEFAULT_MAX_ENTRIES = 5000;
const DEFAULT_MAX_TOTAL_BYTES = 200 * 1024 * 1024; // 200 MB
const DEFAULT_MAX_ENTRY_BYTES = 50 * 1024 * 1024; // 50 MB

const ALLOWED_KEY_EXT_RE = /\.(ya?ml|json|txt)$/i;

/**
 * Quick check for PKZIP signature bytes.
 * @param {Buffer} buf
 * @returns {boolean}
 */
function isZipBuffer(buf) {
  if (!Buffer.isBuffer(buf) || buf.length < 4) return false;
  const sig = buf.readUInt32LE(0);
  return sig === LOCAL_SIGNATURE || sig === EOCD_SIGNATURE || sig === 0x08074b50;
}

/**
 * Locate the End of Central Directory (EOCD) record offset in a ZIP buffer.
 * @param {Buffer} buf
 * @returns {number}
 */
function findEocdOffset(buf) {
  const minOffset = Math.max(0, buf.length - 65557);
  for (let i = buf.length - 22; i >= minOffset; i--) {
    if (buf.readUInt32LE(i) === EOCD_SIGNATURE) {
      const commentLen = buf.readUInt16LE(i + 20);
      if (i + 22 + commentLen === buf.length) {
        return i;
      }
    }
  }
  return -1;
}

/**
 * Extract all file entries from a ZIP buffer using Central Directory metadata.
 * Supports Store (0) and Deflate (8), including streaming ZIPs (data descriptor bit 3)
 * such as those generated by Node's `archiver`.
 *
 * @param {Buffer} buffer
 * @param {object} [options]
 * @returns {Map<string, Buffer>} Map of normalized posix path -> file Buffer
 */
function extractZipEntries(buffer, options = {}) {
  if (!Buffer.isBuffer(buffer) || buffer.length < 22) {
    throw new Error('Invalid ZIP archive: file is empty or truncated');
  }

  const maxEntries = options.maxEntries || DEFAULT_MAX_ENTRIES;
  const maxTotalBytes = options.maxTotalBytes || DEFAULT_MAX_TOTAL_BYTES;
  const maxEntryBytes = options.maxEntryBytes || DEFAULT_MAX_ENTRY_BYTES;

  const eocdOffset = findEocdOffset(buffer);
  if (eocdOffset < 0) {
    throw new Error('Invalid ZIP archive: end of central directory not found');
  }

  const totalEntries = buffer.readUInt16LE(eocdOffset + 10);
  const cdSize = buffer.readUInt32LE(eocdOffset + 12);
  const cdOffset = buffer.readUInt32LE(eocdOffset + 16);

  if (totalEntries === 0xffff || cdSize === 0xffffffff || cdOffset === 0xffffffff) {
    throw new Error('ZIP64 archives are not supported');
  }
  if (totalEntries > maxEntries) {
    throw new Error(`ZIP archive contains too many entries (max ${maxEntries})`);
  }
  if (cdOffset + cdSize > buffer.length) {
    throw new Error('Invalid ZIP archive: central directory out of bounds');
  }

  const entries = new Map();
  let cursor = cdOffset;
  let totalUncompressed = 0;

  for (let i = 0; i < totalEntries; i++) {
    if (cursor + 46 > buffer.length || buffer.readUInt32LE(cursor) !== CD_SIGNATURE) {
      throw new Error('Invalid ZIP archive: corrupt central directory entry');
    }

    const compressionMethod = buffer.readUInt16LE(cursor + 10);
    const compressedSize = buffer.readUInt32LE(cursor + 20);
    const uncompressedSize = buffer.readUInt32LE(cursor + 24);
    const fileNameLen = buffer.readUInt16LE(cursor + 28);
    const extraLen = buffer.readUInt16LE(cursor + 30);
    const commentLen = buffer.readUInt16LE(cursor + 32);
    const localHeaderOffset = buffer.readUInt32LE(cursor + 42);

    const nameStart = cursor + 46;
    const nameEnd = nameStart + fileNameLen;
    if (nameEnd > buffer.length) {
      throw new Error('Invalid ZIP archive: entry name out of bounds');
    }

    const rawName = buffer.slice(nameStart, nameEnd).toString('utf8');
    cursor = nameEnd + extraLen + commentLen;

    // Normalize slashes and strip leading ./ or /
    const normalized = rawName.replace(/\\/g, '/').replace(/^(\.\/|\/)+/, '');
    if (!normalized || normalized.endsWith('/')) {
      continue; // directory entry
    }

    // Reject path traversal segments
    const segments = normalized.split('/');
    if (segments.some(seg => seg === '..')) {
      continue;
    }

    if (uncompressedSize > maxEntryBytes) {
      throw new Error(`ZIP entry "${normalized}" exceeds max allowed size`);
    }
    totalUncompressed += uncompressedSize;
    if (totalUncompressed > maxTotalBytes) {
      throw new Error('ZIP archive exceeds maximum uncompressed size limit');
    }

    if (localHeaderOffset + 30 > buffer.length || buffer.readUInt32LE(localHeaderOffset) !== LOCAL_SIGNATURE) {
      throw new Error(`Invalid ZIP archive: corrupt local header for "${normalized}"`);
    }

    const localNameLen = buffer.readUInt16LE(localHeaderOffset + 26);
    const localExtraLen = buffer.readUInt16LE(localHeaderOffset + 28);
    const dataStart = localHeaderOffset + 30 + localNameLen + localExtraLen;
    const dataEnd = dataStart + compressedSize;

    if (dataEnd > buffer.length) {
      throw new Error(`Invalid ZIP archive: compressed data out of bounds for "${normalized}"`);
    }

    const compressedData = buffer.slice(dataStart, dataEnd);
    let contentBuf;

    if (compressionMethod === 0) {
      contentBuf = Buffer.from(compressedData);
    } else if (compressionMethod === 8) {
      contentBuf = zlib.inflateRawSync(compressedData, { maxOutputLength: maxEntryBytes });
    } else {
      throw new Error(`Unsupported ZIP compression method (${compressionMethod}) for "${normalized}"`);
    }

    if (contentBuf.length > maxEntryBytes) {
      throw new Error(`ZIP entry "${normalized}" exceeds max allowed size`);
    }

    entries.set(normalized, contentBuf);
  }

  return entries;
}

/**
 * Safely parse a JSON Buffer, returning null on invalid JSON.
 * @param {Buffer|undefined} buf
 * @returns {any}
 */
function safeParseJsonBuffer(buf) {
  if (!buf) return null;
  try {
    return JSON.parse(buf.toString('utf8'));
  } catch (_) {
    return null;
  }
}

/**
 * Parse a Telegram / Key Manager backup ZIP buffer into the normalized Key Manager
 * restore bundle shape: { version, createdAt, config, tokenMap, files, hasDatabaseSnapshot }.
 *
 * Supports:
 * 1. Telegram backup archives (`cmp-keys-backup-*.zip`) with:
 *    - `manifest.json`
 *    - `keyserver/config.json`
 *    - `keyserver/token_map.json`
 *    - `keyserver/keys/<filename>`
 *    - optional `database.json`
 * 2. A zipped Key Manager JSON backup (`keymanager-backup-*.json`).
 *
 * @param {Buffer} buffer
 * @returns {{
 *   version: number,
 *   createdAt: string|null,
 *   kind: string,
 *   config: object|null,
 *   tokenMap: object|null,
 *   files: Array<{ filename: string, content: string, size: number }>,
 *   hasDatabaseSnapshot: boolean
 * }}
 */
function parseKeyBackupZip(buffer) {
  const entries = extractZipEntries(buffer);

  // Check if entries are nested inside a single top-level folder (e.g., backup/keyserver/...)
  const findEntry = (relPath) => {
    if (entries.has(relPath)) return entries.get(relPath);
    for (const [k, v] of entries.entries()) {
      if (k.endsWith(`/${relPath}`)) return v;
    }
    return undefined;
  };

  const manifestBuf = findEntry('manifest.json');
  const manifest = safeParseJsonBuffer(manifestBuf);

  const configBuf = findEntry('keyserver/config.json');
  const tokenMapBuf = findEntry('keyserver/token_map.json');

  const config = safeParseJsonBuffer(configBuf);
  const tokenMap = safeParseJsonBuffer(tokenMapBuf);
  const hasDatabaseSnapshot = Boolean(findEntry('database.json'));

  const files = [];
  for (const [entryPath, contentBuf] of entries.entries()) {
    const keysMarker = 'keyserver/keys/';
    const idx = entryPath.indexOf(keysMarker);
    if (idx === -1) continue;
    const rel = entryPath.slice(idx + keysMarker.length);
    if (!rel || rel.includes('/')) continue; // only direct children of keyserver/keys/
    const filename = path.posix.basename(rel);
    if (!filename || !ALLOWED_KEY_EXT_RE.test(filename)) continue;
    files.push({
      filename,
      content: contentBuf.toString('utf8'),
      size: contentBuf.length,
    });
  }

  // Fallback: if no keyserver/* structure was found, check if the ZIP wraps a standard
  // Key Manager JSON backup bundle (e.g. keymanager-backup-*.json)
  if (!manifest && !config && !tokenMap && files.length === 0) {
    for (const [entryPath, contentBuf] of entries.entries()) {
      if (!entryPath.toLowerCase().endsWith('.json')) continue;
      if (path.posix.basename(entryPath).toLowerCase() === 'database.json') continue;
      const parsed = safeParseJsonBuffer(contentBuf);
      if (parsed && typeof parsed === 'object' && parsed.version && Array.isArray(parsed.files)) {
        return {
          version: parsed.version,
          createdAt: parsed.createdAt || parsed.created_at || null,
          kind: 'keymanager-json-in-zip',
          config: parsed.config && typeof parsed.config === 'object' ? parsed.config : null,
          tokenMap: parsed.tokenMap && typeof parsed.tokenMap === 'object' ? parsed.tokenMap : null,
          files: parsed.files,
          hasDatabaseSnapshot,
        };
      }
    }
    throw new Error('Invalid backup ZIP: no keyserver backup files found');
  }

  const isManifestValid = !manifest || !manifest.kind || manifest.kind === 'cmp-keys-and-keyserver-backup';
  if (!isManifestValid) {
    throw new Error(`Unsupported backup archive kind: ${manifest.kind}`);
  }

  return {
    version: (manifest && manifest.version) || 1,
    createdAt: (manifest && (manifest.created_at || manifest.createdAt)) || null,
    kind: (manifest && manifest.kind) || 'cmp-keys-and-keyserver-backup',
    config: config && typeof config === 'object' ? config : null,
    tokenMap: tokenMap && typeof tokenMap === 'object' ? tokenMap : null,
    files,
    hasDatabaseSnapshot,
  };
}

/**
 * Extract `database.json` from a Telegram backup ZIP buffer, if present.
 * @param {Buffer} buffer
 * @returns {object|null}
 */
function extractDatabaseSnapshotFromZip(buffer) {
  const entries = extractZipEntries(buffer);
  let dbBuf = entries.get('database.json');
  if (!dbBuf) {
    for (const [k, v] of entries.entries()) {
      if (k.endsWith('/database.json')) {
        dbBuf = v;
        break;
      }
    }
  }
  return safeParseJsonBuffer(dbBuf);
}

module.exports = {
  isZipBuffer,
  extractZipEntries,
  parseKeyBackupZip,
  extractDatabaseSnapshotFromZip,
};
